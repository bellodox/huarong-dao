import { build } from 'esbuild';
import { readFile,writeFile } from 'node:fs/promises';
import { fileURLToPath,pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

/** Generate identical bytes independent of the invoking directory; no runtime packages. */
export async function relayBuild() {
  const result=await build({
    absWorkingDir:fileURLToPath(new URL('../',import.meta.url)),
    entryPoints:['leaderboard/relay-entry.js'],outfile:'relay.js',bundle:true,
    format:'esm',platform:'neutral',target:'es2022',write:false,metafile:true,
    legalComments:'inline',banner:{js:'// Generated by npm run build:relay. Edit leaderboard/relay-entry.js, not this file.'}
  });
  if(result.outputFiles.length!==1||Object.values(result.metafile.outputs).some(output=>output.imports.length))throw Error('relay_not_self_contained');
  return result.outputFiles[0].contents;
}
/** Check rather than repair stale distributions; used by tests and Wrangler before bundling. */
export async function checkRelay(artifact=new URL('../relay.js',import.meta.url)) {
  const expected=await relayBuild();
  const actual=await readFile(artifact);
  if(!actual.equals(expected))throw Error('stale_relay: run npm run build:relay');
  return expected.length;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href) {
  if(process.argv.slice(2).some(argument=>argument!=='--check'))throw Error('usage: node tests/build-relay.js [--check]');
  if(process.argv.includes('--check'))console.log('PASS current self-contained relay:',await checkRelay(),'bytes');
  else {const bytes=await relayBuild();await writeFile(new URL('../relay.js',import.meta.url),bytes);console.log('Built relay.js:',bytes.length,'bytes');}
}
